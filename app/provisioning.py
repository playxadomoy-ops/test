"""Per-customer provisioning: which server this build belongs to. Nothing here is ever shown to or typed by the user.

``app/provisioning_data.py`` is GENERATED by the customer's server (GUI "Експорт налаштувань" or
server/tools/export_provisioning.py) and bundled into that customer's APK. It contains only PUBLIC material plus the
rotatable enrollment key -- no private key and no per-user credential. Without it the build cannot reach any server
over the Internet (it still supports LAN auto-pairing in a development setup).
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from typing import Optional

from app.services.pairing import normalize_server_code

ENV_OVERRIDE = "AIR_ALERT_PROVISIONING_FILE"  # development/test: path to a JSON bundle


@dataclass(frozen=True)
class Provisioning:
    server_id: str
    server_cert_pem: str
    enroll_key: str
    gateway_url: str


def _validate(raw: object) -> Optional[Provisioning]:
    if not isinstance(raw, dict):
        return None
    server_id = normalize_server_code(raw.get("server_id", ""))
    cert, key, gw = raw.get("server_cert_pem"), raw.get("enroll_key"), raw.get("gateway_url")
    if not (server_id and isinstance(cert, str) and "BEGIN CERTIFICATE" in cert and isinstance(key, str) and key
            and isinstance(gw, str) and gw.startswith(("https://", "http://"))):
        return None
    return Provisioning(server_id, cert, key, gw.rstrip("/"))


def load_provisioning() -> Optional[Provisioning]:
    path = os.environ.get(ENV_OVERRIDE, "").strip()
    if path:
        try:
            with open(path, encoding="utf-8") as fh:
                return _validate(json.load(fh))
        except (OSError, ValueError):
            return None
    try:
        from app import provisioning_data  # type: ignore[attr-defined]
    except ImportError:
        return None
    return _validate(getattr(provisioning_data, "PROVISIONING", None))
